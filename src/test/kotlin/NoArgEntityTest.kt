package io.github.sor2171.backend

import io.github.sor2171.backend.entity.ApiResponse
import io.github.sor2171.backend.entity.dto.Account
import io.github.sor2171.backend.entity.dto.EmailVerificationMsg
import io.github.sor2171.backend.entity.vo.request.EmailRegisterVO
import io.github.sor2171.backend.entity.vo.request.LoginVO
import io.github.sor2171.backend.entity.vo.request.PasswordResetVO
import io.github.sor2171.backend.entity.vo.response.AuthorizeVO
import io.github.sor2171.backend.entity.vo.response.ReloginVO
import kotlin.test.Test
import kotlin.test.assertNotNull

class NoArgEntityTest {

    @Test
    fun testNoArgConstructorsExist() {
        val entityClasses = listOf(
            ApiResponse::class.java,
            Account::class.java,
            EmailVerificationMsg::class.java,
            EmailRegisterVO::class.java,
            LoginVO::class.java,
            PasswordResetVO::class.java,
            AuthorizeVO::class.java,
            ReloginVO::class.java
        )

        for (clazz in entityClasses) {
            val constructor = clazz.getDeclaredConstructor()
            assertNotNull(constructor, "Expected ${clazz.name} to have a no-arg constructor generated by kotlin-noarg")
            constructor.isAccessible = true
            val instance = constructor.newInstance()
            assertNotNull(instance, "Instance of ${clazz.name} should be creatable via no-arg constructor")
        }
    }
}
